package cn.yuanxin.mvp.web.face;

/**
 * 人脸 1:N 搜索的**保守**业务分类（B 自有端口的一部分，供应商无关）。
 *
 * <p>权威依据：{@code backend/doc/后端详细设计-V1-MVP.md:657}「可靠匹配用 namespace + face_subject_ref
 * 定位 T01；<b>歧义不归档，未命中只成为新人候选</b>」，以及 {@code :663}「自动新人判定阈值、活体条件
 * 未通过 PoC，则<b>不得开启真实自动登记</b>」。
 *
 * <p><b>刻意没有 {@code RELIABLE_NEW} 取值</b>：搜索"没匹配"不构成"这是可靠新人"的证据
 * （可能只是阈值、光照、角度或库内缺少该人）。任何需要"可靠新人"语义的调用方都必须自行取得
 * 额外证据，绝不能把 {@link #NO_MATCH} 当作可靠新人。
 */
public enum FaceSearchDecision {

    /**
     * 库内存在唯一、达到阈值且与次优候选有足够间隔的匹配；此时（且仅此时）会给出稳定 {@code subjectRef}。
     * 该值**只**表示"与该 namespace 库内某登记主体高度相似"，不表示现场性、不表示活体、
     * 也不表示该主体已被业务侧建档。
     */
    MATCHED,

    /**
     * 库内无达到阈值的候选（含 namespace 存在但库为空）。<b>不得</b>解释为可靠新人。
     */
    NO_MATCH,

    /**
     * 无法判定：接近但未达阈值、最优与次优间隔不足（歧义）、或输入质量不足。
     * 业务侧必须与 {@link #NO_MATCH} 一样按"未通过核验"处理，绝不放行。
     */
    UNCERTAIN
}
